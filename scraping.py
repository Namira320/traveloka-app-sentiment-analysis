from google_play_scraper import reviews, Sort
import pandas as pd

# Target aplikasi: Traveloka (Bisa diganti dengan 'com.agoda.mobile.consumer' untuk Agoda)
target_app = 'com.traveloka.android'
target_samples = 10000

print(f"Menembak API Google Play Store untuk {target_samples} ulasan {target_app}...")

# Proses penarikan data langsung melalui API backend
all_reviews, _ = reviews(
    target_app,
    lang='id',       # Ambil ulasan berbahasa Indonesia
    country='id',    # Region Indonesia
    sort=Sort.NEWEST,# Ambil dari yang paling terbaru
    count=target_samples
)

# Ekstraksi dan pembersihan data langsung ke format yang siap dipakai analisis
df = pd.DataFrame(all_reviews)[['content', 'score']]
df.columns = ['content', 'rating']

file_name = 'dataset_ulasan_hotel_traveloka.csv'
df.to_csv(file_name, index=False, encoding='utf-8')
print(f"{len(df)} data berhasil disimpan ke '{file_name}'")